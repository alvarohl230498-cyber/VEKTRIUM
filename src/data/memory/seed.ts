function buildLightPhases(
  projectId: string,
  upToOrder: number,
  taskSeeds: Array<{ order: number; title: string; status: Task['status']; weight: number; dueOffset: number | null }>,
): ProjectPhaseWithTasks[] {
  const templates = buildPhasesForProject(projectId).slice(0, upToOrder + 1)

  const phases: ProjectPhaseWithTasks[] = templates.map((t) => ({
    id: `${projectId}-phase-${t.order}`,
    projectId: t.projectId,
    order: t.order,
    name: t.name,
    description: t.description,
    weight: t.weight,
    plannedStart: null,
    plannedEnd: null,
    isIllustrative: true,
    tasks: [],
  }))

  for (const seed of taskSeeds) {
    const phase = phases[seed.order]
    if (!phase) continue
    phase.tasks.push({
      id: `${projectId}-task-${seed.order}-${phase.tasks.length}`,
      projectId,
      phaseId: phase.id,
      title: seed.title,
      status: seed.status,
      weight: seed.weight,
      assigneeId: 'user-alvaro',
      dueDate: seed.dueOffset === null ? null : offsetDays(seed.dueOffset),
      completedAt: seed.status === 'completada' ? offsetDays((seed.dueOffset ?? 0) - 1) : null,
      isIllustrative: true,
    })
  }

  return phases
}

