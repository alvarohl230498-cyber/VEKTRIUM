const DAY_MS = 24 * 60 * 60 * 1000

function offsetDays(days: number, hour = 15, minute = 0): string {
  const base = new Date()
  base.setHours(hour, minute, 0, 0)
  return new Date(base.getTime() + days * DAY_MS).toISOString()
}

